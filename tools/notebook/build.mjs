import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir, cp } from 'node:fs/promises';
import { dirname, resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
for (const id of ['notebook', 'markdown', 'archive', 'epub', 'subtitles']) {
  const fonts = id === 'notebook' || id === 'markdown';
  const vendor = resolve(root, `../../plugins/${id}/vendor`);
  await mkdir(vendor, { recursive: true });
  const result = await build({
    absWorkingDir: root, entryPoints: [id === 'notebook' ? 'main.mjs' : `${id}-main.mjs`], outfile: join(vendor, `${id}.js`),
    bundle: true, minify: true, format: 'iife', platform: 'browser', target: ['safari17'],
    metafile: true, legalComments: 'external',
    banner: { js: '// Generated by tools/notebook/build.mjs. See THIRD_PARTY_LICENSES.txt.' }
  });

  // Preserve the complete licenses of packages whose code actually reaches the bundle.
  const packages = new Set(fonts ? ['node_modules/katex'] : []);
  for (const output of Object.values(result.metafile.outputs)) {
    for (const [name, info] of Object.entries(output.inputs)) {
      if (!info.bytesInOutput || !name.includes('node_modules/')) continue;
      let dir = dirname(resolve(root, name));
      while (dir.startsWith(root)) {
        try {
          const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
          if (pkg.name && pkg.version) { packages.add(relative(root, dir)); break; }
        } catch (_) { /* walk up past nested module-type markers */ }
        dir = dirname(dir);
      }
    }
  }
  let licenses = 'Third-party code bundled in this Spacebar plugin.\n\n';
  for (const dir of [...packages].sort()) {
    const path = resolve(root, dir);
    const pkg = JSON.parse(await readFile(join(path, 'package.json'), 'utf8'));
    const files = (await readdir(path)).filter(name => /^(license|copying)(\.|$)/i.test(name));
    licenses += `\n=== ${pkg.name} ${pkg.version} (${pkg.license}) ===\n`;
    if (!files.length) {
      if (pkg.name.startsWith('@jupyterlab/')) {
        licenses += '\n' + await readFile(join(root, 'licenses/jupyterlab.txt'), 'utf8') + '\n';
      } else if (pkg.name.startsWith('@lumino/')) {
        licenses += '\n' + await readFile(join(root, 'licenses/lumino.txt'), 'utf8') + '\n';
      } else { throw new Error(`Missing license: ${pkg.name}`); }
    }
    for (const file of files) licenses += '\n' + await readFile(join(path, file), 'utf8') + '\n';
  }
  if (fonts) licenses += '\n=== KaTeX fonts (SIL OFL 1.1) ===\n' + await readFile(join(root, 'licenses/katex-fonts.txt'), 'utf8');
  await writeFile(join(vendor, 'THIRD_PARTY_LICENSES.txt'), licenses.trimEnd() + '\n');
  if (fonts) await cp(join(root, 'node_modules/katex/dist/katex.min.css'), join(vendor, 'katex.min.css'));
  if (fonts) await cp(join(root, 'node_modules/katex/dist/fonts'), join(vendor, 'fonts'), { recursive: true });
  if (id !== 'notebook') await cp(join(root, 'viewer.css'), resolve(vendor, '../style.css'));
  console.log(`Built ${id} viewer with ${packages.size} bundled packages.`);
}
