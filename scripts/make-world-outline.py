#!/usr/bin/env python3 -I
"""turn a natural earth land geojson into plugins/geojson/world.js:
a compact array of rings (lon/lat pairs rounded to 1 decimal, consecutive
duplicates dropped, rings with fewer than 4 points dropped).

usage: python3 -I scripts/make-world-outline.py <ne_110m_land.geojson> <out.js>
source: https://github.com/nvkelso/natural-earth-vector (public domain)
"""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
with open(src) as f:
    data = json.load(f)

rings = []
for feature in data["features"]:
    geom = feature["geometry"]
    polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
    for poly in polys:
        outer = poly[0]  # outer ring only; holes don't matter at this scale
        pts = []
        for lon, lat in outer:
            p = (round(lon, 1), round(lat, 1))
            if not pts or pts[-1] != p:
                pts.append(p)
        if len(pts) >= 4:
            rings.append(pts)

flat = [[c for p in r for c in p] for r in rings]
js = "// world land outline, natural earth 110m, public domain. generated by scripts/make-world-outline.py\n"
js += "// rings of [lon, lat, lon, lat, ...]\n"
js += "window.WORLD_RINGS = " + json.dumps(flat, separators=(",", ":")) + ";\n"
with open(out, "w") as f:
    f.write(js)
print(f"{len(rings)} rings, {sum(len(r) for r in rings)} points, {len(js)} bytes -> {out}")
